/**
 * 現在のパス名に合致するヘルプコンテンツを取得するヘルパー
 */
export function getPageHelpContent(pathname: string): PageHelpContent {
  // 完全一致
  if (PAGE_HELP_DATA[pathname]) {
    return PAGE_HELP_DATA[pathname];
  }

  // 接頭辞一致 (例: /event/edit, /score/confirm 等)
  const segments = pathname.split("/").filter(Boolean);
  if (segments.length > 0) {
    const rootPath = `/${segments[0]}`;
    if (PAGE_HELP_DATA[rootPath]) {
      const base = PAGE_HELP_DATA[rootPath];
      // サブパスに応じたカスタマイズ
      if (segments.includes("edit") || segments.includes("create")) {
        return {
          ...base,
          title: `${base.title.replace("の使い方", "")} - 編集・作成の使い方`,
          summary: "各項目の入力や設定を行い、右下の保存ボタンで登録を完了します。",
        };
      }
      if (segments.includes("confirm") || segments.includes("detail")) {
        return {
          ...base,
          title: `${base.title.replace("の使い方", "")} - 詳細確認の使い方`,
          summary: "登録された詳細データの確認や編集導線、関連アクションを行う画面です。",
        };
      }
      return base;
    }
  }

  // デフォルトフォールバック
  return {
    title: "このページの使い方",
    icon: faCircleQuestion,
    summary: "Sound Solution Orchestra（愛大軽音）の活動ポータル「Solu Navi」の操作画面です。",
    sections: [
      {
        title: "💡 基本的な操作方法",
        items: [
          "上部のパンくずリストから前の階層やホーム画面に戻ることができます。",
          "ヘッダー右上のメニューアイコンから各機能（カレンダー、譜面、メディア、部費等）へ自由に移動できます。",
          "右上の更新アイコン（くるくる矢印）を押すと、最新のデータに即座に更新されます。",
        ],
      },
    ],
    tips: [
      "操作に迷ったときは、画面右下のAIコンシェルジュ（チャット）に質問することもできます。",
    ],
  };
}
